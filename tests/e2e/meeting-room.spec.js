const { test, expect } = require('@playwright/test');

test('one room carries identities and votes between poker and poll', async ({ page, browser, request }) => {
  await page.goto('/meeting-room');
  await page.getByLabel('Room name').fill('Refinement together');
  await page.getByRole('button', { name: 'Create meeting room', exact: true }).click();
  await expect(page).toHaveURL(/meeting-room\/[a-z0-9]{6}$/);
  const url = page.url(), id = url.split('/').at(-1), api = '/meeting-room/api/rooms/' + id;
  await page.locator('bw-wife-picker [data-testid="pick"]').first().click();
  await page.getByRole('button', { name: 'Join meeting', exact: true }).click();
  await expect(page.getByText('Run the meeting', { exact: true })).toBeVisible();
  const otherContext = await browser.newContext();
  const other = await otherContext.newPage();
  await other.goto(url);
  await other.locator('bw-wife-picker [data-testid="pick"]').first().click();
  await other.getByRole('button', { name: 'Join meeting', exact: true }).click();
  await expect(other.getByText('Ready when you are', { exact: true })).toBeVisible();
  await page.getByLabel('Story or question').fill('Story one');
  await page.getByRole('button', { name: 'Start activity', exact: true }).click();
  await other.locator('#activity').getByRole('button', { name: '8', exact: true }).click();
  await expect(page.locator('#activity')).toContainText('1 response');
  let state = await (await request.get(api)).json();
  const pokerId = state.activeId;
  expect(state.sessions[0].activities[0].results).toBeNull();
  expect(JSON.stringify(state)).not.toContain('secretHash');
  await page.getByLabel('Next activity').selectOption('poll');
  await page.getByLabel('Story or question').fill('Ship today?');
  await page.getByLabel('Poll options').fill('Yes\nNo');
  await page.getByRole('button', { name: 'Start activity', exact: true }).click();
  await other.locator('#activity').getByRole('button', { name: 'Yes', exact: true }).click();
  await expect(other.locator('#activity')).toContainText('Vote saved');
  await page.getByRole('button', { name: 'Close poll', exact: true }).click();
  await expect(other.locator('#activity')).toContainText('Yes: 1');
  await page.getByRole('button', { name: 'Resume Story one', exact: true }).click();
  await expect(other.locator('#activity h2')).toHaveText('Story one');
  await page.getByRole('button', { name: 'Reveal cards', exact: true }).click();
  await expect(other.locator('#activity')).toContainText('Median: 8');
  await page.reload();
  await expect(page.locator('#activity')).toContainText('Median: 8');
  await page.getByRole('button', { name: 'Re-vote', exact: true }).click();
  await expect(other.locator('#activity')).toContainText('0 responses');
  await page.getByRole('button', { name: 'End meeting', exact: true }).click();
  await page.getByRole('button', { name: 'Start new meeting', exact: true }).click();
  state = await (await request.get(api)).json();
  expect(state.sessions).toHaveLength(2);
  expect(state.members).toHaveLength(2);
  expect(state.sessions[0].activities.find(a => a.id === pokerId).phase).toBe('closed');
  // History is a local view: it does not move other participants.
  await page.locator('#history').getByRole('button', { name: /♠ Story one/ }).click();
  await expect(page.locator('#activity h2')).toHaveText('Story one');
  await expect(other.locator('#activity h2')).toHaveText('Ready when you are');
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.locator('body').evaluate(el => el.clientWidth));
  await otherContext.close();
});
